"""Generate the model card (docs/model_card.md) from the pipeline's own outputs.

A model card is the standard one-document summary of a model for reviewers,
risk committees and regulators: what it is for, how well it works, for whom it
works less well, and how it is monitored. Generating it from result files means
the numbers in the card can never drift from the numbers the code produced.
"""
from __future__ import annotations

from datetime import date

import pandas as pd


def _pct(x, digits=1) -> str:
    return "n/a" if x is None or pd.isna(x) else f"{100 * float(x):.{digits}f}%"


def _num(x, digits=3) -> str:
    return "n/a" if x is None or pd.isna(x) else f"{float(x):.{digits}f}"


def md_table(rows: list[dict], columns: list[tuple[str, str, callable]]) -> str:
    """columns: (header, key, formatter)."""
    head = "| " + " | ".join(h for h, _, _ in columns) + " |"
    rule = "| " + " | ".join("---" for _ in columns) + " |"
    body = ["| " + " | ".join(fmt(r.get(k)) for _, k, fmt in columns) + " |" for r in rows]
    return "\n".join([head, rule, *body])


def render(*, stage2: dict, comparison: pd.DataFrame, stage3: dict, fairness: dict, flags: list[str],
           importance: pd.DataFrame, example_reasons: list[str], n_features: int, n_train: int,
           n_holdout: int, n_test: int, additivity: dict) -> str:
    sig = stage2["best_challenger_vs_scorecard_holdout"]
    champ = comparison[comparison["model"] == stage2["champion"]].iloc[0]
    score = comparison[comparison["model"] == "scorecard"].iloc[0]
    a = stage3["assumptions"]
    cal = stage3["calibration"]["champion"]
    s = str

    perf = md_table(
        [{**champ.to_dict(), "model": "Champion (" + stage2["champion"].replace("_", " ") + ")"},
         {**score.to_dict(), "model": "Scorecard (benchmark)"}],
        [("Model", "model", s), ("CV AUC", "cv_auc", _num), ("Holdout AUC", "holdout_roc_auc", _num),
         ("Gini", "holdout_gini", _num), ("KS", "holdout_ks", _num), ("PR-AUC", "holdout_pr_auc", _num),
         ("Brier", "holdout_brier", lambda v: _num(v, 4))])

    grid_rows = [{**r, "range": f"{_pct(r['pd_from'])}–{_pct(r['pd_to'])}"} for r in stage3["pricing_grid"]]
    grid = md_table(grid_rows, [("Band", "band", s), ("PD range", "range", s), ("Share of applicants", "share", _pct),
                                ("Mean PD", "mean_pd", _pct), ("Rate", "rate", _pct), ("Decision", "decision", s)])

    bands = md_table(
        [r for r in stage3["band_performance_test"] if r["decision"] == "approve"],
        [("Band", "band", s), ("Loans", "loans", lambda v: f"{int(v):,}"), ("Predicted PD", "predicted_pd", _pct),
         ("Actual default rate", "observed_default_rate", _pct),
         ("Realised margin", "realised_margin", lambda v: _pct(v, 2)),
         ("Target", "target_margin", lambda v: _pct(v, 0))])

    value = md_table(
        stage3["champion_vs_scorecard"],
        [("Approval rate", "approval_rate", lambda v: _pct(v, 0)),
         ("Champion default rate", "champion_default_rate", lambda v: _pct(v, 2)),
         ("Scorecard default rate", "scorecard_default_rate", lambda v: _pct(v, 2)),
         ("Defaults avoided per 10k", "defaults_avoided_per_10k_applicants", lambda v: f"{float(v):.0f}"),
         ("Extra profit per 10k", "extra_profit_per_10k_applicants", lambda v: f"{float(v) / 1e6:.1f} million")])

    top = md_table(
        importance.head(10).to_dict(orient="records"),
        [("Feature", "label", s), ("Share of total influence", "share", _pct)])

    fair_sections = []
    for attribute, table in fairness.items():
        rows = table[table["reportable"]].to_dict(orient="records")
        fair_sections.append(f"**By {attribute.replace('_', ' ')}** (test half, groups with enough applicants)\n\n" + md_table(
            rows,
            [("Group", "group", s), ("Applicants", "applicants", lambda v: f"{int(v):,}"),
             ("Actual default rate", "default_rate", _pct), ("Mean predicted PD", "mean_predicted_pd", _pct),
             ("Calibration gap", "calibration_gap", lambda v: f"{100 * float(v):+.2f} pts"),
             ("AUC", "auc", _num), ("Approval rate", "approval_rate", _pct),
             ("Adverse impact ratio", "adverse_impact_ratio", lambda v: _num(v, 2)),
             ("Good-customer approval", "good_customer_approval_rate", _pct)]))
    flag_text = "\n".join(f"- {f}" for f in flags) if flags else "- No group crossed a warning threshold."

    reasons = "\n".join(f"{i + 1}. {r}" for i, r in enumerate(example_reasons) if r) or "_No example available._"
    caveats = "\n".join(f"- {c}" for c in stage3["caveats"])

    return f"""# Model card: credit risk scoring and risk-based loan pricing

_Generated by `python -m src.explain_and_audit` on {date.today().isoformat()} from the pipeline's own result files. Do not edit by hand; re-run to update._

## Summary

A probability-of-default (PD) model for consumer loan applicants, used to place each applicant in a risk band, set a risk-based interest rate, decline applicants whose required rate exceeds the cap, and give the top reasons behind every score. Champion: **{stage2['champion'].replace('_', ' ')}**. Against the logistic-regression scorecard, the best challenger ({stage2['best_challenger'].replace('_', ' ')}) changes holdout AUC by **{sig['auc_difference']:+.3f}** (95% CI {sig['ci95_low']:+.3f} to {sig['ci95_high']:+.3f}).

## Intended use

- Estimate the probability that a consumer-loan applicant will have payment difficulties.
- Set the interest rate by risk band, and decline bands that cannot be priced profitably under the rate cap.
- Give applicants and credit officers the main reasons behind each score.
- Support, not replace, human credit decisions: declines and borderline cases should be reviewable by a person.

**Not intended for:** other products, countries or time periods without revalidation; fully automated decisions without human oversight; any use of gender, age or other protected attributes as inputs.

## Data

- Home Credit Default Risk (Kaggle): {n_train + n_holdout:,} historical applicants with known outcomes, plus credit-bureau history, previous applications and repayment records.
- Target: payment difficulties on the loan, used as a proxy for default.
- Split: {n_train:,} for training and tuning; {n_holdout:,} held out, never used for training or model selection. The holdout is split again into a calibration half and a test half ({n_test:,} applicants) for pricing and fairness checks.
- {n_features} features built in SQL (affordability ratios, bureau debt and arrears, refusal history, repayment behaviour). Gender and age are stored separately and **never** enter the model; they are used only for the fairness checks below.

## Performance on held-out applicants

{perf}

## Calibration

Cross-validation chose **{cal['method']}** as the calibration method. Expected calibration error on the test half: **{_num(cal['test_after']['ece'], 4)}** (predicted default rate {_pct(cal['test_after']['mean_predicted'], 2)} vs actual {_pct(cal['test_after']['observed_rate'], 2)}).

## Risk-based pricing

Rate = (margin + funding + operating cost + PD × LGD) / (1 − PD), with LGD {_pct(a['lgd'], 0)}, funding {_pct(a['cost_of_funds'], 0)}, operating cost {_pct(a['operating_cost'], 0)}, target margin {_pct(a['target_margin'], 0)} and a {_pct(a['max_rate'], 0)} rate cap. Assumptions are illustrative and set in `config/config.yaml`.

{grid}

**Check on unseen applicants:** realised margin by approved band.

{bands}

**Value of the better model** (same flat price, same approval rate):

{value}

## Explainability

Each score is decomposed into per-feature contributions with TreeSHAP (native in LightGBM and XGBoost). The ensemble's contributions are averaged in log-odds; they reproduce the champion's probabilities to within {_pct(additivity['mean_abs_probability_diff'], 2)} on average (correlation {_num(additivity['correlation'], 4)}).

Most influential features overall:

{top}

Example reason codes for a declined applicant:

{reasons}

## Fairness

{chr(10).join(fair_sections)}

**Warnings** (four-fifths rule for approval, calibration gap over 1 point, AUC gap over 0.03):

{flag_text}

Differences in approval rate can reflect genuine differences in risk; the stronger warning signs are lower accuracy (AUC) or systematic over-prediction (positive calibration gap) for a group. Any flag above should be reviewed by risk and compliance before deployment.

## Limitations and risks

{caveats}
- Features such as employment length or region can act as proxies for protected attributes; fairness must be re-checked after every retrain.
- Data are historical and from a single lender; behaviour may shift (economic conditions, new products, new customer segments).

## Monitoring plan

- **Monthly:** population stability (PSI) of the score and top features; retrain review if PSI exceeds 0.25.
- **Quarterly:** calibration and realised margin by band as loans mature (watch any band whose defaults run above prediction); fairness metrics by gender and age.
- **On any retrain:** rerun this audit and regenerate this card; the champion must beat the current model on the same holdout with a confidence interval above zero.

## Regulatory context

- **EU AI Act:** credit scoring of individuals is classed as high-risk, which requires risk management, data governance, documentation, transparency, human oversight and accuracy monitoring. This card, the decision log and the fairness report are designed to support that.
- **GDPR / Kenya Data Protection Act 2019:** people have rights around automated decisions and the use of their data. The model uses no protected attributes as inputs, every score has reasons, and decisions are designed to be human-reviewable.
"""

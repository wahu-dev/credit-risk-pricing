"""Package everything the API needs into one versioned file.

    python -m src.build_serving
    python -m src.build_serving --sample      # CI

Creates:
  models/serving_bundle.joblib      models, calibrator, price grid, labels,
                                    typical values, reference data for monitoring
  models/serving_requirements.txt   exact library versions the models were
                                    trained with, for the Docker image

Why pin versions: the models are saved with pickle (joblib). Loading them with
a different scikit-learn / LightGBM / XGBoost version can fail or, worse,
silently change predictions. The image installs exactly what trained them.
"""
from __future__ import annotations

import argparse
import logging
import platform
from datetime import datetime, timezone
from importlib.metadata import PackageNotFoundError, version

import joblib
import numpy as np
import pandas as pd

from src.config import load_config, project_path
from src.explain import binary_features
from src.model_data import holdout_halves, holdout_split, load_model_table, training_rows
from src.scoring import champion_probability, load_bundle

log = logging.getLogger("build_serving")

# pyarrow is needed to *load* the bundle: pandas 3 stores text columns (e.g. the
# price grid's band names) with pyarrow, so unpickling them requires it.
SERVING_PACKAGES = ["numpy", "pandas", "pyarrow", "scikit-learn", "scipy", "lightgbm", "xgboost",
                    "joblib", "pyyaml", "fastapi", "uvicorn", "pydantic"]
REFERENCE_SIZE = 20_000
N_MONITORED = 8


def build(sample: bool = False) -> dict:
    cfg = load_config()
    seed = cfg["project"]["random_seed"]
    suffix = "_sample" if sample else ""
    models_dir = project_path(cfg["models"]["models_dir"])
    bundle = load_bundle(models_dir / f"stage2_models{suffix}.joblib")
    pricing = load_bundle(models_dir / f"pricing{suffix}.joblib")

    table = load_model_table(cfg, sample)
    rows, y = training_rows(table)
    train_idx, holdout_idx = holdout_split(y, cfg["baseline"]["test_size"], seed)
    encoder, columns = bundle["encoder"], bundle["columns"]
    raw_train = rows.iloc[train_idx][columns]

    typical = raw_train.median(numeric_only=True).to_dict()
    example = {}
    for c in columns:
        if c in encoder.columns:
            example[c] = str(raw_train[c].mode().iloc[0])
        elif str(raw_train[c].dtype).startswith("int"):
            example[c] = int(round(typical[c]))
        else:
            example[c] = None if pd.isna(typical.get(c)) else round(float(typical[c]), 4)

    # Reference population for drift monitoring: the calibration half of the
    # holdout (unseen in training), scored exactly as the API will score.
    cal_pos, _ = holdout_halves(y.iloc[holdout_idx].to_numpy(), cfg["pricing"]["calibration_share"], seed)
    ref_rows = holdout_idx[cal_pos]
    rng = np.random.default_rng(seed)
    if len(ref_rows) > REFERENCE_SIZE:
        ref_rows = np.sort(rng.choice(ref_rows, REFERENCE_SIZE, replace=False))
    X_ref = encoder.transform(rows.iloc[ref_rows])[columns]
    ref_pd = pricing["calibrators"]["champion"].transform(champion_probability(bundle, X_ref))

    monitored = _monitored_features(cfg, columns, encoder.columns, suffix)
    versions = {}
    for pkg in SERVING_PACKAGES:
        try:
            versions[pkg] = version(pkg)
        except PackageNotFoundError:
            log.warning("%s is not installed; it will be unpinned in serving_requirements.txt", pkg)

    created = datetime.now(timezone.utc)
    serving = {
        "model_version": f"{bundle['champion']}-{created:%Y%m%d%H%M}",
        "created_at": created.isoformat(timespec="seconds"),
        "bundle": bundle,
        "calibrator": pricing["calibrators"]["champion"],
        "grid": pricing["grid"],
        "assumptions": pricing["assumptions"],
        "labels": cfg["explain"]["labels"],
        "top_reasons": cfg["explain"]["top_reasons"],
        "categories": {c: encoder.categories_[c] for c in encoder.columns},
        "typical": {k: float(v) for k, v in typical.items() if pd.notna(v)},
        "dtypes": {c: str(raw_train[c].dtype) for c in columns},
        "binary_features": sorted(binary_features(raw_train.drop(columns=list(encoder.columns)))),
        "example": example,
        "monitored_features": monitored,
        "reference": {"pd": ref_pd.astype(float), **{f: X_ref[f].to_numpy(dtype=float) for f in monitored}},
        "versions": {"python": platform.python_version(), **versions},
    }
    path = models_dir / f"serving_bundle{suffix}.joblib"
    joblib.dump(serving, path)

    reqs = [f"{pkg}=={versions[pkg]}" if pkg in versions else pkg for pkg in SERVING_PACKAGES]
    (models_dir / "serving_requirements.txt").write_text(
        "# Generated by src.build_serving: the exact versions that trained the models.\n" + "\n".join(reqs) + "\n",
        encoding="utf-8")

    py = ".".join(platform.python_version_tuple()[:2])
    log.info("Serving bundle %s written to %s", serving["model_version"], path)
    log.info("Monitored features: %s", monitored)
    log.info("Run the API locally:   uvicorn src.api:app --port 8000")
    log.info("Build the Docker image: docker build --build-arg PYTHON_VERSION=%s --build-arg BUNDLE=%s "
             "-t credit-risk-api .", py, path.relative_to(project_path(".")).as_posix())
    return serving


def _monitored_features(cfg: dict, columns: list[str], categorical: list[str], suffix: str) -> list[str]:
    """Top features by SHAP influence (stage 4), else the first labelled ones."""
    influence = project_path(cfg["reports_dir"]) / f"audit{suffix}" / "feature_influence.csv"
    numeric = [c for c in columns if c not in categorical]
    if influence.exists():
        ranked = [f for f in pd.read_csv(influence)["feature"] if f in numeric]
    else:
        ranked = [f for f in cfg["explain"]["labels"] if f in numeric]
    return ranked[:N_MONITORED]


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the serving bundle for the API")
    parser.add_argument("--sample", action="store_true")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-7s %(name)s: %(message)s")
    build(sample=args.sample)


if __name__ == "__main__":
    main()
